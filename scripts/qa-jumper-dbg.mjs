import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 900, height: 800 } });
await page.goto("http://127.0.0.1:8080/play/jumper", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /^Play$/i }).click();
await page.waitForTimeout(400);
const samples = [];
const read = () => page.evaluate(() => (window).__jumperDbg);
samples.push({ t: "start", ...(await read()) });
await page.keyboard.down("KeyA");
await page.waitForTimeout(100);
samples.push({ t: "a100", ...(await read()) });
await page.waitForTimeout(400);
samples.push({ t: "a500", ...(await read()) });
await page.keyboard.up("KeyA");
await page.waitForTimeout(100);
samples.push({ t: "aUp", ...(await read()) });
await page.keyboard.down("KeyD");
await page.waitForTimeout(100);
samples.push({ t: "d100", ...(await read()) });
await page.waitForTimeout(400);
samples.push({ t: "d500", ...(await read()) });
await page.keyboard.up("KeyD");
await page.waitForTimeout(50);
samples.push({ t: "dUp", ...(await read()) });
console.log(JSON.stringify(samples, null, 2));
await browser.close();
